#!/usr/bin/env python3
"""BGE-QE and LLM-Q2E over BM25 and DPH on one or more collections (all judged queries); runs saved for run_baselines.py metrics.

  python scripts/run_qe_baselines.py --corpus scifact nfcorpus

BGE-QE: for each query term the 50 nearest neighbours among the 15,000 most frequent terms of the collection
(BGE-small-en-v1.5 vectors of their most frequent surface forms, built once into data/cache/qe_vocab/), their union scored by
the qtf-weighted mean cosine to the query terms, the best ten added with a total weight of (1 - 0.6) / 0.6 times the query
mass, in proportion to their scores.
LLM-Q2E: keywords generated by qwen3.5:4b (Ollama, temperature 0, at most 64 tokens, no thinking) for the prompt in
evaluation.baselines.pyterrier_qe.DEFAULT_QE_CONFIG, appended to five copies of the analysed query. The generations are
REPLAYED from the keyword cache data/cache/qe_llm/raw/<sha256 of the query>[:24].json (the stored generations of the paper;
a fresh generation differs on about half of the queries). Any call to the LLM server is blocked: a query missing from the
cache stops the run.
Both rewriters emit already stemmed terms, so retrieval runs with termpipelines=NoOp (crve.pipeline.baselines.run_qe).
"""

from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
os.chdir(ROOT)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", nargs="+", required=True)
    ap.add_argument("--runs-dir", default="data/cache/runs")
    a = ap.parse_args()
    from crve.pipeline import baselines as BL
    from crve.pipeline import common as C
    C.pin_terrier()
    BL.run_qe(a.corpus, a.runs_dir, noop=True)


if __name__ == "__main__":
    main()
